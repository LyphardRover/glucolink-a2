-- Purpose: Shared namespaces, run log and v3 D1 rule parameters.
-- Reads: pg_catalog. Writes: eight schema comments and two shared tables.
-- Design link: architecture_v2; governance and reporting configuration.
-- Run after: provision a database and select its object-owner role.
-- Re-runnable: yes; refresh parameters transactionally, preserve all run history.
-- Parameter source: task card v3 D1; nine final named values.
-- Deployment: verify target connection, current definitions and backup outside this file.
-- All nine parameters use text so dates and numbers share one interface.
-- Consumers explicitly cast param_value to date/integer/numeric.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
-- Create the eight namespaces without replacing existing objects.
CREATE SCHEMA IF NOT EXISTS src_gp;
CREATE SCHEMA IF NOT EXISTS src_lab;
CREATE SCHEMA IF NOT EXISTS src_pharm;
CREATE SCHEMA IF NOT EXISTS raw;
CREATE SCHEMA IF NOT EXISTS cleansed;
CREATE SCHEMA IF NOT EXISTS curated;
CREATE SCHEMA IF NOT EXISTS reporting;
CREATE SCHEMA IF NOT EXISTS audit;
-- Document layer purpose and responsible packages.
COMMENT ON SCHEMA src_gp IS 'GP source system: clinics, patient registrations and encounters. Owner: C.';
COMMENT ON SCHEMA src_lab IS 'Laboratory source system: patients and FHIR observations/deliveries. DDL: C; message data: B.';
COMMENT ON SCHEMA src_pharm IS 'Pharmacy source system: pharmacies, patients, medications and dispensing. Owner: C.';
COMMENT ON SCHEMA raw IS 'RAW / bronze: unchanged source copies plus ingestion provenance. Owner: C.';
COMMENT ON SCHEMA cleansed IS 'CLEANSED / silver: standardisation, data quality and patient identity resolution. Owner: D.';
COMMENT ON SCHEMA curated IS 'CURATED / gold: conformed dimensions and event-grain facts. Owner: E.';
COMMENT ON SCHEMA reporting IS 'Shared rule parameters (A/B) and use-case views UC1/UC3 (E), UC2/UC4 (D).';
COMMENT ON SCHEMA audit IS 'Pipeline run log (B/C), evaluation-only identity truth (C) and test results (F).';
-- Existing run history is never cleared by setup. C supplies pipeline_name/status.
CREATE TABLE IF NOT EXISTS audit.pipeline_run (
 run_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pipeline_name text NOT NULL,
 started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 finished_at timestamptz,
 rows_read bigint NOT NULL DEFAULT 0 CHECK (rows_read >= 0),
 rows_loaded bigint NOT NULL DEFAULT 0 CHECK (rows_loaded >= 0),
 rows_rejected bigint NOT NULL DEFAULT 0 CHECK (rows_rejected >= 0),
 status text NOT NULL DEFAULT 'RUNNING' CHECK (status IN ('RUNNING','SUCCESS','FAILED')),
 error_message text,
 CHECK (finished_at IS NULL OR finished_at >= started_at)
);
COMMENT ON TABLE audit.pipeline_run IS 'One pipeline execution per row; written explicitly by pipeline scripts, not a full SQL audit trail.';
-- Store shared business thresholds as explicitly cast text values.
CREATE TABLE IF NOT EXISTS reporting.rule_parameter (
 param_name text PRIMARY KEY,
 param_value text NOT NULL,
 description text NOT NULL
);
COMMENT ON TABLE reporting.rule_parameter IS 'Nine shared prototype parameters from task card v3 D1; rule owner A. Cast values explicitly.';
